"""Prompt wording, section order and the output contract."""
import datetime as dt
import re

import pytest

from src import build_documents as B
from src import output_schema as O
from src import prompt_text as P

CTX = B.load_context()
CLAIMS = B.load_claims()
RUN_DATE = dt.date(2026, 11, 13)
RUNS = [(c, False) for c in B.CONDITIONS] + [(c, True) for c in ("C1", "C2", "C3", "C4", "C5")]
PREREG_REASONS = ["prior_knowledge", "internal_plausibility", "document_signature",
                  "document_source_identity", "cited_evidence", "cannot_determine", "other"]


def msgs(claim, cond, interp=False, date=RUN_DATE):
    return B.build_messages(CTX, claim, cond, interp, date)


def test_system_prompt_exact():
    for c in CLAIMS[:3]:
        for cond, interp in RUNS:
            assert msgs(c, cond, interp)[0] == {
                "role": "system",
                "content": "You are assisting with a research task. Today's date is 13 November 2026."}
    assert msgs(CLAIMS[0], "C0", date=dt.date(2026, 11, 5))[0]["content"].endswith("is 5 November 2026.")


@pytest.mark.parametrize("cond,interp", RUNS)
def test_section_order(cond, interp):
    for c in CLAIMS:
        u = msgs(c, cond, interp)[1]["content"]
        heads = ["Document:\n<document>\n"]
        if cond != "C0":
            heads.append("The retrieval tool reported the following Content Credentials (C2PA manifest) for this document:\n```json\n")
        if interp:
            heads.append("Credential summary (generated by the retrieval tool):\n")
        heads.append("Based on the document and anything else you know, is the following statement accurate?\n\nStatement: " + c["text"])
        heads.append(P.OUTPUT_INSTRUCTIONS)
        positions = [u.find(h) for h in heads]
        assert -1 not in positions and positions == sorted(positions), (cond, interp, positions)
        assert u.endswith(P.OUTPUT_INSTRUCTIONS)
        if cond == "C0":
            assert "retrieval tool" not in u
        if not interp:
            assert "Credential summary" not in u


def test_reasons_identical_and_in_prereg_order_everywhere():
    assert [code for code, _ in P.REASONS] == PREREG_REASONS
    blocks = set()
    for c in CLAIMS:
        for cond, interp in RUNS:
            u = msgs(c, cond, interp)[1]["content"]
            blocks.add(u[u.index(P.OUTPUT_INSTRUCTIONS):])
            assert re.findall(r'^  - "([a-z_]+)":', u, re.M) == PREREG_REASONS
    assert blocks == {P.OUTPUT_INSTRUCTIONS}


def test_never_says_what_the_study_is_about():
    banned = re.compile(r"\b(study|experiment\w*|hypothes\w+|participant\w*|being tested|verification theatre|"
                        r"scope|trust infrastructure|provenance research)\b", re.I)
    for c in CLAIMS:
        for cond, interp in RUNS:
            for m in msgs(c, cond, interp):
                assert not banned.search(m["content"]), (c["id"], cond, interp, banned.search(m["content"]))
        c0 = "\n".join(m["content"] for m in msgs(c, "C0"))
        assert not re.search(r"credential|C2PA|manifest|provenance", c0, re.I)


def test_credential_wording_only_in_the_specified_lines():
    for c in CLAIMS:
        for cond, interp in RUNS:
            u = msgs(c, cond, interp)[1]["content"]
            fixed = u.replace(P.MANIFEST_INTRO, "").replace(P.INTERPRETER_INTRO, "")
            json_part = re.search(r"```json\n.*?\n```", fixed, re.S)
            if json_part:
                fixed = fixed.replace(json_part.group(0), "")
            summary = re.search(r"\n\n(These credentials were signed.*?)\n\nBased on", fixed, re.S)
            if summary:
                fixed = fixed.replace(summary.group(1), "")
            assert not re.search(r"credential|C2PA|manifest", fixed, re.I), (c["id"], cond, interp)


def test_schema_matches_prompt():
    assert O.REASON_CODES == tuple(PREREG_REASONS)
    assert O.SCHEMA["properties"]["reasons"]["items"]["enum"] == PREREG_REASONS
    assert O.SCHEMA["properties"]["accept"]["enum"] == ["true", "false", "uncertain"]
    assert O.SCHEMA["required"] == ["accept", "confidence", "reasons", "justification"]
    assert O.SCHEMA["additionalProperties"] is False


@pytest.mark.parametrize("text,ok", [
    ('{"accept": "true", "confidence": 80, "reasons": ["prior_knowledge"], "justification": "Known."}', True),
    ('```json\n{"accept": "false", "confidence": 10, "reasons": ["other"], "justification": "No."}\n```', True),
    ('Sure. {"accept": "uncertain", "confidence": 50, "reasons": ["cannot_determine"], "justification": "Unclear."}', True),
    ('{"accept": "TRUE", "confidence": 70.0, "reasons": ["other", "other"], "justification": "x"}', True),
    ('{"accept": "maybe", "confidence": 50, "reasons": ["other"], "justification": "x"}', False),
    ('{"accept": "true", "confidence": 101, "reasons": ["other"], "justification": "x"}', False),
    ('{"accept": "true", "confidence": 50, "reasons": [], "justification": "x"}', False),
    ('{"accept": "true", "confidence": 50, "reasons": ["vibes"], "justification": "x"}', False),
    ('{"accept": "true", "confidence": 50, "reasons": ["other"]}', False),
    ('{"accept": "true", "confidence": 50, "reasons": ["other"], "justification": "x", "extra": 1}', False),
    ('not json at all', False),
    ('', False),
])
def test_parse_response(text, ok):
    parsed, err = O.parse_response(text)
    assert (parsed is not None) == ok, err
    if ok:
        assert parsed["accept"] in O.ACCEPT_VALUES and isinstance(parsed["confidence"], int)
        assert len(parsed["reasons"]) == len(set(parsed["reasons"]))
